"""Generated Business Requirements Documents.

One row per **generation attempt**, not per document (ADR-024). A failed
attempt is a row carrying its reason, which makes "how often does the model
return something unusable" a SQL question rather than log archaeology.

The markdown lives in the row. The API's filesystem is a container's, so a file
written during a request is gone on the next deploy; and the row has to exist
anyway, because Phase 3 generates tests from a BRD and needs to know which
issue it belongs to, who asked for it, and which prompt produced it.
"""

from __future__ import annotations

from datetime import datetime
from enum import StrEnum
from uuid import UUID

from sqlalchemy import (
    CheckConstraint,
    Computed,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
    Uuid,
    text,
)
from sqlalchemy.orm import Mapped, mapped_column

from app.core.database import Base
from app.models.base import TimestampMixin, TimestampTZ, UUIDPrimaryKeyMixin
from app.models.jira_issue import ISSUE_KEY_PATTERN

_ISSUE_KEY_LENGTH = 64
_PROJECT_KEY_LENGTH = 32
_EMAIL_LENGTH = 320


class BrdStatus(StrEnum):
    """Where a generation attempt ended up.

    ``PENDING`` exists because generation is two steps: the prompt is built and
    the row opened, then the model answers. A row that stays ``PENDING`` is a
    generation that never came back, which is a thing worth being able to see.
    """

    PENDING = "pending"
    READY = "ready"
    NEEDS_INFO = "needs_info"
    FAILED = "failed"


#: Statuses where the attempt is over, whether or not it produced a document.
TERMINAL_BRD_STATUSES = frozenset({BrdStatus.READY, BrdStatus.NEEDS_INFO, BrdStatus.FAILED})

#: Statuses that must carry markdown. ``NEEDS_INFO`` does: the model's open
#: questions are the document in that case, and they are what a person reads.
_STATUSES_WITH_MARKDOWN = (BrdStatus.READY, BrdStatus.NEEDS_INFO)

_STATUS_SQL_LIST = ", ".join(f"'{s.value}'" for s in BrdStatus)
_WITH_MARKDOWN_SQL_LIST = ", ".join(f"'{s.value}'" for s in _STATUSES_WITH_MARKDOWN)


class BrdDocument(UUIDPrimaryKeyMixin, TimestampMixin, Base):
    """One attempt at generating a BRD for one Jira issue."""

    __tablename__ = "brd_documents"

    issue_key: Mapped[str] = mapped_column(String(_ISSUE_KEY_LENGTH), nullable=False)
    # Generated by the database, exactly as on jira_issues and for the same
    # reason: the project key is what the access check compares against
    # user_project_access, so it must not be able to drift from the issue key.
    project_key: Mapped[str] = mapped_column(
        String(_PROJECT_KEY_LENGTH),
        Computed("split_part(issue_key, '-', 1)", persisted=True),
        nullable=False,
    )

    # No foreign key to jira_issues. The cache row can be evicted or refetched
    # independently, and a BRD must outlive it: the document is evidence of
    # what was agreed, not a view over the current ticket.

    status: Mapped[str] = mapped_column(String(16), nullable=False, default=BrdStatus.PENDING.value)

    #: The document, normalised -- no code fence, no preamble. NULL while
    #: pending and when the attempt failed.
    markdown: Mapped[str | None] = mapped_column(Text, nullable=True)

    requirement_count: Mapped[int | None] = mapped_column(Integer, nullable=True)
    scenario_count: Mapped[int | None] = mapped_column(Integer, nullable=True)
    open_question_count: Mapped[int | None] = mapped_column(Integer, nullable=True)

    #: Identifies the prompt pair that produced this, e.g. ``brd_v1``. Makes
    #: "why does this document look like that" answerable months later.
    prompt_version: Mapped[str] = mapped_column(String(32), nullable=False)

    #: The model the provider said answered, not the one we asked for. Named
    #: ``reported`` so nobody reads it as a model this platform chose.
    model_reported: Mapped[str | None] = mapped_column(String(128), nullable=True)

    prompt_tokens: Mapped[int | None] = mapped_column(Integer, nullable=True)
    completion_tokens: Mapped[int | None] = mapped_column(Integer, nullable=True)

    #: Denormalised, as on audit_logs: the trail must survive the user row
    #: being deleted. Lowercased, per ADR-017.
    actor_email: Mapped[str] = mapped_column(String(_EMAIL_LENGTH), nullable=False)
    actor_user_id: Mapped[UUID | None] = mapped_column(
        Uuid(as_uuid=True), ForeignKey("users.id", ondelete="SET NULL"), nullable=True
    )

    #: Why a failed attempt failed. A short reason, never a traceback and never
    #: the model's own words: the reply is untrusted text (ADR-023) and this
    #: column is read by people and by SQL.
    failure_reason: Mapped[str | None] = mapped_column(String(64), nullable=True)

    finished_at: Mapped[datetime | None] = mapped_column(TimestampTZ, nullable=True)

    __table_args__ = (
        CheckConstraint(f"status IN ({_STATUS_SQL_LIST})", name="brd_status"),
        CheckConstraint(f"issue_key ~ '{ISSUE_KEY_PATTERN}'", name="issue_key_format"),
        CheckConstraint("actor_email = lower(actor_email)", name="actor_email_lowercase"),
        # A finished attempt has a finish time and a pending one does not.
        # Postgres evaluates this on every write, so a bug in the service
        # cannot leave a row that looks both finished and in progress.
        CheckConstraint(
            f"(status IN ({_WITH_MARKDOWN_SQL_LIST}, '{BrdStatus.FAILED.value}'))"
            " = (finished_at IS NOT NULL)",
            name="terminal_status_has_finished_at",
        ),
        # A document exists exactly when the status says one does. Without
        # this, a 'ready' row with no markdown is reachable by any bug in the
        # service, and every reader would need a null check for a state that
        # should be impossible.
        CheckConstraint(
            f"(status IN ({_WITH_MARKDOWN_SQL_LIST})) = (markdown IS NOT NULL)",
            name="document_status_has_markdown",
        ),
        CheckConstraint(
            f"(status = '{BrdStatus.FAILED.value}') = (failure_reason IS NOT NULL)",
            name="failed_status_has_reason",
        ),
        CheckConstraint(
            "requirement_count IS NULL OR requirement_count >= 0",
            name="requirement_count_non_negative",
        ),
        CheckConstraint(
            "scenario_count IS NULL OR scenario_count >= 0",
            name="scenario_count_non_negative",
        ),
        # Serves "the current BRD for this issue", which is the newest ready
        # row -- the query every caller makes (ADR-024).
        Index("ix_brd_documents_issue_key_created_at", "issue_key", "created_at"),
        Index("ix_brd_documents_project_key", "project_key"),
        # Serves "what did this person generate?" for the audit question, and
        # "what is still pending?" for the stuck-generation question.
        Index("ix_brd_documents_actor_email_created_at", "actor_email", "created_at"),
        Index(
            "ix_brd_documents_pending",
            "created_at",
            postgresql_where=text(f"status = '{BrdStatus.PENDING.value}'"),
        ),
    )

    def __repr__(self) -> str:
        """Identify the document by issue and status."""
        return f"<BrdDocument {self.issue_key} {self.status}>"
